/** Fill {name}-style placeholders. */
export function fmt(template, vars = {}) {
    return String(template).replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

/** Resolve the UI language from the setting and the browser locale. */
export function resolveUiLang(setting, locale = '') {
    if (setting === 'th' || setting === 'en') return setting;
    return String(locale).toLowerCase().startsWith('th') ? 'th' : 'en';
}
